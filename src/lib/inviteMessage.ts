/**
 * 发给朋友的整段邀请语。**故意不 import 任何东西**——客户端组件要用它拼剪贴板内容。
 *
 * 为什么要有这个：一次一次地贴邀请码、贴链接、再口头解释一遍怎么用，
 * 摩擦全在这儿，邀请三个朋友就懒得邀了。做成一段现成的话，点一下进剪贴板，
 * 直接粘到微信就完事。
 *
 * 内容上有意写全两件**不说就一定会踩坑**的事：
 *   1. 家长端和孩子端是同一个账号、靠登录时勾不勾「这是孩子的设备」区分。
 *      勾了之后 /admin 会被弹回孩子端（见 src/proxy.ts）——不提前说的话，
 *      朋友在孩子平板上勾了，然后会以为自己被锁死了。
 *   2. 运维者技术上能看到对方的数据。后台那页写着"建议提前告知他们"，
 *      那就不该指望家长每次自己记得说，直接写进邀请语里。
 *
 * origin 由调用方传 window.location.origin：他现在从哪个地址访问后台，
 * 朋友拿到的就是哪个地址。写死或者读环境变量的话，换域名就得改代码。
 */
export function inviteMessage(origin: string, code: string): string {
  return [
    "邀请你一起用「打卡小星星」帮孩子记打卡 🌟",
    "",
    `① 打开 ${origin}/signup`,
    `② 邀请码：${code}（只能用一次）`,
    "③ 填邮箱和密码注册，然后给孩子建个档案",
    "",
    "【玩法二选一，建议选宝可梦】",
    "孩子完成任务挣「阳光」，用来换你们商量好的奖励，剩下的投进玩法里。",
    "· 宝可梦图鉴：买精灵球去抓，386 只按打卡等级一批批解锁；",
    "  抓到的永久留在牌库里，每只还能点进去看进化路线和怕什么属性。",
    "· 种花园：种植物集齐一套换回阳光，但每收获一次花园就清空重来。",
    "推荐宝可梦——内容够玩好几年，而且收藏是一直往上累积的，不会清零。",
    "",
    "【家长端和孩子端是两个地方，用的是同一个账号】",
    // 用 ☐ / ☑ 而不是 Markdown 的 **粗体**：这段话是要粘到微信的，
    // 星号会原样显示出来；方框符号正好对应界面上那个复选框，一眼就懂。
    "· 你自己手机上：☐ 不勾「这是孩子的设备」→ 进后台，批任务、管奖励",
    "· 孩子的平板上：☑ 勾上「这是孩子的设备」→ 锁在孩子端，他点不进后台改自己的分数",
    "· 真要在孩子平板上进后台：点孩子端最下面那行很小的「家长登录 →」重新登录一次",
    "· 孩子端的地址在后台「孩子档案」里，建完档案就能看到",
    "",
    "⚠️ 系统跑在我的服务器上，技术上我能看到你家的数据，介意的话先跟我说。",
  ].join("\n");
}
